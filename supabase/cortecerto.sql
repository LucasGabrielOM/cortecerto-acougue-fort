  table_name text;
begin
  foreach table_name in array array[
    'products', 'break_reports', 'break_items', 'time_offs', 'user_profiles'
  ]
  loop
    execute format('drop policy if exists "Authenticated users manage data" on public.%I', table_name);
    execute format(
      'create policy "Authenticated users manage data" on public.%I for all to authenticated using (true) with check (true)',
      table_name
    );
  end loop;
end $$;

