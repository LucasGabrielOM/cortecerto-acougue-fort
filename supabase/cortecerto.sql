create table if not exists public.products (
  id bigint generated by default as identity primary key,
  code text,
  name text not null unique,
  category text not null default 'Bovina',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.break_reports (
  id bigint generated by default as identity primary key,
  date date not null,
  requisition text not null default '',
  employee text not null,
  total_kg numeric(12,3) not null default 0,
  total_cost numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.break_items (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.break_reports(id) on delete cascade,
  product_id bigint references public.products(id),
  product_code text not null default '',
  product_name text not null,
  quantity_kg numeric(12,3) not null check (quantity_kg > 0),
  cost numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

alter table public.products add column if not exists code text;
alter table public.break_items add column if not exists product_code text not null default '';
create unique index if not exists products_code_unique
  on public.products (code)
  where code is not null and code <> '';

create table if not exists public.time_offs (
  id bigint generated by default as identity primary key,
  employee text not null,
  date date not null,
  type text not null default 'Semanal',
  status text not null default 'Solicitada'
    check (status in ('Solicitada', 'Confirmada', 'Realizada')),
  coverage text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.user_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null,
  store text not null default 'Fort Atacadista • Barreiros',
  username text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.break_reports enable row level security;
alter table public.break_items enable row level security;
alter table public.time_offs enable row level security;
alter table public.user_profiles enable row level security;

